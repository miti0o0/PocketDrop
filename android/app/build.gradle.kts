    }

    signingConfigs {
        val storeFile = signingValue("storeFile", "POCKETDROP_KEYSTORE")
        if (storeFile != null) {
            create("release") {
                this.storeFile = file(storeFile)
                storePassword = signingValue("storePassword", "POCKETDROP_KEYSTORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "POCKETDROP_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "POCKETDROP_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
