// Release signing is read from android/keystore.properties (not committed) or from environment
// variables in CI. Without it, release builds are signed with the debug key.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? = keystoreProps.getProperty(key) ?: System.getenv(env)

android {
    namespace = "app.pocketdrop"
    compileSdk = 34

    defaultConfig {
        applicationId = "app.pocketdrop"
        minSdk = 24
